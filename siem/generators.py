"""Generate QRadar AQL queries and Shuffle playbooks from an alert.

Without an API key these use deterministic templates. With a key, the LLM
refines the human-readable parts (playbook description, hunting hint) but the
structural output stays template-driven so it is always valid.

The README warns that generated AQL/Shuffle must be reviewed on the user's own
QRadar and Shuffle before use.
"""
from __future__ import annotations

import json
from datetime import datetime, timezone

from common import llm

# Per-rule hint for what to hunt for in the SIEM.
_HUNT = {
    "R1_TOOL_POISONING": "mcpMethod = 'tools/list' AND risk IN ('high','critical')",
    "R2_SENSITIVE_FILE": "mcpTool = 'read_file' AND cat = 'blocked'",
    "R3_EXFILTRATION": "mcpTool = 'send_email' AND risk IN ('high','critical')",
    "R4_RUG_PULL": "ruleId = 'R4_RUG_PULL'",
    "R5_DATA_INJECTION": "mcpMethod ILIKE 'tools/call%' AND cat = 'redacted'",
    "R6_TASK_MISMATCH": "ruleId = 'R6_TASK_MISMATCH'",
    "R0_SOAR_BLOCKLIST": "cat = 'blocked'",
}


def generate_aql(alert: dict, hours: int = 1) -> str:
    """A QRadar Ariel (AQL) query to find the same activity in the SIEM."""
    rule_id = alert.get("rule_id", "")
    server = alert.get("server", "")
    tool = alert.get("tool") or ""
    extra = _HUNT.get(rule_id, f"ruleId = '{rule_id}'")
    where = [f"\"mcpServer\" = '{server}'"]
    if tool:
        where.append(f"\"mcpTool\" = '{tool}'")
    where.append(f"({extra})")
    where_clause = " AND ".join(where)
    return (
        "SELECT devTime, mcpServer, mcpTool, ruleId, ruleName, frameworkTag, "
        "sessionId, reason, sev\n"
        "FROM events\n"
        f"WHERE LOGSOURCETYPENAME(devicetype) = 'AgentSOC MCP-Firewall'\n"
        f"  AND {where_clause}\n"
        f"ORDER BY devTime DESC\n"
        f"LAST {hours} HOURS"
    )


def generate_shuffle(alert: dict) -> dict:
    """A Shuffle (SOAR) playbook as JSON: get alert -> enrich -> block -> notify."""
    aid = alert.get("id", "")
    server = alert.get("server", "")
    tool = alert.get("tool") or ""
    risk = alert.get("risk", "medium")
    base_url = "${AGENTSOC_URL}"
    return {
        "name": f"AgentSOC-Respond-{alert.get('rule_id','RULE')}",
        "description": (
            f"Respond to AgentSOC alert {aid} ({alert.get('title','')}). "
            f"Framework: {alert.get('tag','')}. Review before enabling in production."
        ),
        "trigger": {"type": "webhook", "source": "AgentSOC", "filter": {"risk": risk}},
        "actions": [
            {
                "id": "get_alert", "app": "HTTP", "action": "GET",
                "url": f"{base_url}/alerts/{aid}",
                "description": "Fetch the full alert and its event chain.",
            },
            {
                "id": "enrich", "app": "AgentSOC", "action": "get_rules",
                "url": f"{base_url}/alerts/{aid}/rules",
                "description": "Pull the matching AQL query to hunt for related activity.",
            },
            {
                "id": "block_tool", "app": "AgentSOC", "action": "block_tool",
                "url": f"{base_url}/soar/block",
                "body": {"server": server, "tool": tool},
                "description": f"Quarantine tool '{tool}' on server '{server}' at the proxy.",
                "condition": f"risk in ['high','critical']",
            },
            {
                "id": "notify_analyst", "app": "Email", "action": "send",
                "to": "soc-team@corp.example",
                "subject": f"[AgentSOC][{risk.upper()}] {alert.get('title','')}",
                "body": (
                    f"Alert {aid} on {server}/{tool}.\n"
                    f"Rule: {alert.get('rule_id')} — {alert.get('reason','')}\n"
                    f"Framework: {alert.get('tag','')}\n"
                    f"Action taken by AgentSOC: {alert.get('action','')}."
                ),
                "description": "Notify the SOC analyst for triage.",
            },
        ],
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "note": "Generated by AgentSOC. Validate on your own Shuffle instance before use.",
    }


def enrich_descriptions(alert: dict, aql: str, shuffle: dict) -> dict:
    """Optionally let the LLM improve the human-readable text. No key => unchanged."""
    if not llm.has_key():
        return shuffle
    system = (
        "You are a SOC automation engineer. Improve ONLY the natural-language description "
        "fields of this Shuffle playbook so an analyst understands the response at a glance. "
        "Do not change action ids, urls, or structure. Reply with the full JSON playbook."
    )
    schema = {"type": "object", "additionalProperties": True}
    out = llm.ask_json(system, json.dumps({"alert": alert, "playbook": shuffle}, ensure_ascii=False),
                       schema, max_tokens=1500)
    if out and isinstance(out, dict) and out.get("actions"):
        return out
    return shuffle


def generate_rules(alert: dict, hours: int = 1) -> dict:
    """Bundle AQL + Shuffle for an alert."""
    aql = generate_aql(alert, hours=hours)
    shuffle = generate_shuffle(alert)
    shuffle = enrich_descriptions(alert, aql, shuffle)
    return {
        "aql": aql,
        "shuffle": shuffle,
        "mode": "llm" if llm.has_key() else "template",
    }
